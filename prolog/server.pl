% --- endpoints -------------------------------------------------------------

% The page talks to the endpoints below and hardcodes no rule data. The limits,
% the carrier list, the city codes and the routing grammar all come from
% /api/ruleset, so the UI cannot drift away from the ruleset it describes.
home(Request) :-
    reply_asset('/', Request).

static(Request) :-
    memberchk(path(Path), Request),
    (   asset(Path, _, _)
    ->  reply_asset(Path, Request)
    ;   http_404([], Request)
    ).

% Headers first, then the bytes exactly as they are. The stream switches to
% octet once the headers are written. Headers are ASCII either way, and the body
% must not be re-encoded on its way out or a woff2 arrives corrupt.
%
% Caching depends on whether a file's name identifies its contents. Fonts are
% never edited in place -- a different font means a differently named file -- so
% they are immutable. Everything else is rebuilt under the name it already had,
% so it is revalidated on every load. That now includes a 2.5 MB engine and a
% 400 KB image, but revalidating an unchanged file costs a 304 rather than the
% whole file, and these are usually served over loopback.
%
% Content-Length is left to the HTTP layer, which buffers the reply and counts it
% for us. Writing one here as well produced the header twice.
reply_asset(Path, _Request) :-
    asset(Path, Type, Baked),
    (   from_disk(Path, Fresh)
    ->  Bytes = Fresh
    ;   Bytes = Baked
    ),
    cache_control(Type, Cache),
    format('Content-Type: ~w~n', [Type]),
    format('Cache-Control: ~w~n~n', [Cache]),
    set_stream(current_output, encoding(octet)),
    format('~s', [Bytes]).

from_disk(Path, Bytes) :-
    dev_assets,
    asset_file(File, Path, _),
    asset_root(Root),
    atomic_list_concat([Root, File], Abs),
    catch(read_file_to_string(Abs, Bytes, [encoding(octet)]), _, fail).

% A dev reply must not be cached at all. Otherwise the next edit is invisible,
% for a reason that takes an hour to find.
cache_control(_, 'no-store') :- dev_assets, !.
cache_control('font/woff2', 'public, max-age=31536000, immutable') :- !.
cache_control(_,            'no-cache').

