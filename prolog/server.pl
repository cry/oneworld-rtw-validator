% The UI is read into the program at load time rather than opened from disk on
% each request. There are two reasons, and both bit the first version:
%
%   * A path resolved with prolog_load_context/2 is fixed at *compile* time. So a
%     saved state or an image built anywhere but the deployment directory served
%     404s for a file that was sitting right there. Reading at compile time is
%     the cure, not the disease: what gets baked in is the content, which is what
%     we want, rather than a path that will not exist later.
%   * It takes the only filesystem access out of the request path, so the
%     container can run read-only and the server needs no working directory.
%
% Each asset is held as a *string* of bytes rather than as text. One code path
% then serves the stylesheet and the fonts alike, and nothing has to think about
% the encoding of a woff2. A missing file fails the build, which is where a
% missing UI file should be noticed.
%
% Using a string instead of the code list this once was is not a matter of
% style. A code list costs roughly seventy-five times the size of the file it
% came from: reading the 2.5 MB WebAssembly bundle that way peaked at 194 MB,
% against 19 MB as a string, and the page cannot be served at all without that
% bundle. SWI stores a string of bytes as a byte array, and format/2's ~s writes
% one back out unchanged, so a font round-trips byte for byte. The suite checks
% that.
%
% Everything under web/ except index.html is generated by `npm run build` and
% committed. See the notes in app.src.css, map.src.js and tools/build_image.mjs.
% Nothing in the image knows about npm.
%
% The page runs the validator itself, compiled to WebAssembly, and never calls
% the API below. That is why the two largest assets here are a Prolog engine and
% a Prolog image. The endpoints stay for callers that are not browsers.
:- dynamic asset/3.               % Path, ContentType, Bytes

asset_file('index.html',                        '/',                                 'text/html; charset=UTF-8').
asset_file('app.css',                           '/app.css',                          'text/css; charset=UTF-8').
asset_file('app.js',                            '/app.js',                           'text/javascript; charset=UTF-8').
asset_file('api.js',                            '/api.js',                           'text/javascript; charset=UTF-8').
asset_file('worker.js',                         '/worker.js',                        'text/javascript; charset=UTF-8').
asset_file('map.js',                            '/map.js',                           'text/javascript; charset=UTF-8').
asset_file('rtw.pvm',                           '/rtw.pvm',                          'application/octet-stream').
asset_file('vendor/swipl-bundle-no-data.js',    '/vendor/swipl-bundle-no-data.js',   'text/javascript; charset=UTF-8').
asset_file('fonts/archivo-latin-var.woff2',     '/fonts/archivo-latin-var.woff2',    'font/woff2').
asset_file('fonts/martianmono-latin-var.woff2', '/fonts/martianmono-latin-var.woff2', 'font/woff2').

:- dynamic asset_root/1.          % where they were read from, for dev mode only

:- prolog_load_context(directory, Dir),
   file_directory_name(Dir, Root),
   atomic_list_concat([Root, '/web/'], Web),
   assertz(asset_root(Web)),
   forall(asset_file(File, Path, Type),
          ( atomic_list_concat([Web, File], Abs),
            read_file_to_string(Abs, Bytes, [encoding(octet)]),
            assertz(asset(Path, Type, Bytes)) )).

% Development only. Reading the page into the program is right for a deployment
% and wrong for the twenty minutes you spend editing a stylesheet, because every
% edit needs a restart before it shows up. With RTW_DEV_ASSETS set, each request
% re-reads the file instead, and replies become uncacheable so the browser does
% not defeat the point of it.
%
% It is opt-in, announced at startup, and falls back to the copy in the program
% if the file has gone. The build path it reads from is the one baked in at
% compile time, which is correct on the machine that did the compiling and
% nowhere else.
:- dynamic dev_assets/0.

:- initialization(configure_dev_assets).

configure_dev_assets :-
    (   getenv('RTW_DEV_ASSETS', V),
        V \== '', V \== '0', V \== 'false'
    ->  assertz(dev_assets),
        asset_root(Root),
        print_message(warning, rtw_dev_assets(Root))
    ;   true
    ).

% Access logging is off unless RTW_HTTP_LOG names a file. Otherwise
% library(http/http_log) writes httpd.log into the working directory, which is
% not something merely loading this file should do.
:- initialization(configure_logging).

configure_logging :-
    (   getenv('RTW_HTTP_LOG', File), File \== ''
    ->  set_setting(http:logfile, File)
    ;   set_setting(http:logfile, '')
    ).

% Validation is the only expensive handler. It runs under a time limit and is
% quadratic in the segment count. If it shared the server's default five
% workers, five slow requests would stop /api/health answering, and a load
% balancer would pull the instance out of service over something that is not an
% outage. Its own bounded pool keeps the cheap endpoints responsive. A full
% queue is refused rather than piled up: SWI maps threads_in_pool/1 to a 503,
% which is the honest answer to "we are at capacity".
:- multifile thread_pool:create_pool/1.

thread_pool:create_pool(rtw_validate) :-
    limit(validate_workers, Workers),
    limit(validate_backlog, Backlog),
    thread_pool_create(rtw_validate, Workers, [backlog(Backlog)]).

