/** <module> HTTP front end.

    A second renderer over the same report/3 term the CLI prints. It holds no
    rule logic of its own.

    On concurrency: SWI's HTTP server is multithreaded, and everything below the
    report term is pure. annotate/2 returns a term, no rule asserts anything, and
    the reference data is static and consulted at load time. So handlers share no
    request state and need no locking. It is also why itineraries arrive as JSON
    rather than as Prolog fact files: consulting a fact file changes the global
    database, and could not be done concurrently.
*/

