airports(Request) :-
    cors_enable,
    http_parameters(Request,
                    [ q(Q, [default('')]),
                      limit(Limit, [integer, default(20)])
                    ]),
    Capped is max(1, min(Limit, 100)),
    (   Q == ''
    ->  Results = []
    ;   airport_search(Q, Capped, Codes),
        maplist(airport_json, Codes, Results)
    ),
    reply_json_dict(_{ query: Q, results: Results }).

validate_endpoint(Request) :-
    cors_enable,
    (   memberchk(method(options), Request)
    ->  reply_json_dict(_{}, [status(200)])
    ;   catch_with_backtrace(validate_request(Request), Error,
                             reply_error(Error, Request))
    ).

% The same itinerary written as a routing. It exists so the browser never has to
% write one itself, which would be a second definition of the grammar, and the
% only one with no test behind it. Every report already carries the routing in
% its annotations. This endpoint is for when you want it without asking for a
% verdict.
routing_endpoint(Request) :-
    cors_enable,
    (   memberchk(method(options), Request)
    ->  reply_json_dict(_{}, [status(200)])
    ;   catch_with_backtrace(routing_request(Request), Error,
                             reply_error(Error, Request))
    ).

% What the journey earns. This runs no fare rules at all. A journey that cannot
% be sold can still be priced for its earn, and a perfectly valid one can be
% unpriceable. That is why it is its own endpoint rather than a field on the
% report. See PLANS/05-loyalty-earning.md.
earn_endpoint(Request) :-
    cors_enable,
    (   memberchk(method(options), Request)
    ->  reply_json_dict(_{}, [status(200)])
    ;   catch_with_backtrace(earn_request(Request), Error,
                             reply_error(Error, Request))
    ).

earn_request(Request) :-
    check_body_size(Request),
    http_read_json_dict(Request, Dict, [value_string_as(string)]),
    limit(request_time_limit_seconds, Seconds),
    call_with_time_limit(Seconds, build_earn(Dict, Json)),
    reply_json_dict(Json).

build_earn(Dict, Json) :-
    asked_programs(Dict, Asked),
    resolve_programs(Asked, Programs),
    itinerary_from_json(Dict, Itin),
    annotate(Itin, A),
    earn(A, Programs, Report),
    earn_json(Report, Json).

% Missing or empty means every registered programme, which is the useful
% default. "Where should I credit this ticket?" is the whole reason for having
% more than one, and it cannot be asked one programme at a time.
asked_programs(Dict, Asked) :-
    (   get_dict(programs, Dict, List), is_list(List)
    ->  maplist([V, A]>>( atom_string(A, V) ), List, Asked)
    ;   get_dict(programs, Dict, V), V \== null
    ->  throw(input_error('"programs" must be a list of programme ids.'))
    ;   Asked = []
    ).

routing_request(Request) :-
    check_body_size(Request),
    http_read_json_dict(Request, Dict, [value_string_as(string)]),
    itinerary_from_json(Dict, Itin),
    annotate(Itin, A),
    (   annotated_route(A, Route)
    ->  reply_json_dict(_{ route: Route })
    ;   no_routing_message(A, Message),
        throw(input_error(Message))
    ).

validate_request(Request) :-
    check_body_size(Request),
    http_read_json_dict(Request, Dict, [value_string_as(string)]),
    % The report is built under a time limit and sent outside it, so a timeout
    % can never leave half a response on the wire.
    limit(request_time_limit_seconds, Seconds),
    call_with_time_limit(Seconds, build_report(Dict, Json)),
    reply_json_dict(Json).

build_report(Dict, Json) :-
    itinerary_from_json(Dict, Itin),
    validate_annotated(Itin, Report, A),
    annotations_json(A, Annotations),
    report_json(Report, _{ annotations: Annotations }, Json).

% Refuse an oversized body before reading it, not after. The declared length is
% what SWI will read, so checking it here is the cheap guard. The segment cap in
% io/json_in.pl is the one that bounds the actual work.
%
% A body with no declared length is refused rather than read. Guarding only the
% declared case left the guard easy to sidestep: a chunked request carries no
% Content-Length, http_read_json_dict/3 then reads to end of stream with no
% bound, and the segment cap cannot help because it applies to a document that
% has already been read into memory. Requiring the length is the whole fix. An
% itinerary is a few kilobytes, and every HTTP client declares a length for a
% body that size, so nothing legitimate is turned away. 411 is the status that
% says exactly this, rather than blaming the content.
check_body_size(Request) :-
    limit(max_request_bytes, Max),
    (   memberchk(content_length(Length), Request)
    ->  (   Length > Max
        ->  throw(request_too_large(Length, Max))
        ;   true
        )
    ;   throw(length_required(Max))
    ).

% Malformed input is a 400 with a structured body. Anything else is a bug in a
% rule, and is reported as a 500 rather than swallowed into a verdict.
%
% The four cases below describe the caller's own request back to them, which is
% information they already have. The fallback does not, on purpose: see
% log_internal_error/2.
%
% Working out the reply is kept separate from writing it, so what the client is
% told can be tested without an HTTP context. test_json.pl checks that the
% fallback body carries nothing from the exception term.
%
% The status is decided once and then asked about. Calling error_reply/3 a
% second time with 500 already bound would match the catch-all clause for *every*
% exception, and log each malformed request as an internal failure.
reply_error(Error, Request) :-
    error_reply(Error, Status, Dict),
    (   Status == 500
    ->  log_internal_error(Error, Request)
    ;   true
    ),
    reply_json_dict(Dict, [status(Status)]).

%! error_reply(+Error, -Status, -Dict) is det.
error_reply(input_error(Message), 400,
            _{ error: 'invalid_request', message: Message }) :- !.
error_reply(request_too_large(Length, Max), 413,
            _{ error: 'request_too_large', message: M }) :- !,
    format(atom(M), 'Request body is ~d bytes; the maximum is ~d.', [Length, Max]).
error_reply(length_required(Max), 411,
            _{ error: 'length_required', message: M }) :- !,
    format(atom(M),
           'Request must declare a Content-Length; the maximum accepted is ~d bytes.',
           [Max]).
error_reply(time_limit_exceeded, 503,
            _{ error: 'timeout',
               message: 'Validation exceeded its time limit.' }) :- !.
error_reply(http_reply(_), 400,
            _{ error: 'invalid_request',
               message: 'Request body must be JSON.' }) :- !.
error_reply(_, 500,
            _{ error: 'internal_error',
               message: 'The validator failed on this request. The failure has been logged.' }).

% Logged in full on the server, and opaque to the client. This path only fires
% on a bug, and the raw term plus its backtrace is exactly what a developer
% needs. It is also a description of the validator's internals, and handing that
% to an unauthenticated caller is the hazard library(http/http_error) exists to
% warn about. stderr is the right place for it: systemd and Docker both collect
% stderr, and neither needs a log file managed inside the container.
%
% We print the term ourselves rather than leave it to print_message/2, which
% renders anything without a message clause as "Unknown message". Standard
% errors are then printed a second time so their backtrace, collected by
% catch_with_backtrace/3, is rendered too.
log_internal_error(Error, Request) :-
    (   memberchk(path(Path), Request) -> true ; Path = unknown ),
    print_message(error, rtw_request_failed(Path, Error)),
    (   Error = error(_, _)
    ->  print_message(error, Error)
    ;   true
    ).

